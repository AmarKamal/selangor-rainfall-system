CREATE DEFINER=`root`@`localhost` PROCEDURE `sp_calculate_rolling_rainfall` (IN `p_location_id` VARCHAR(10), IN `p_target_date` DATE)   BEGIN
    DECLARE v_1day DECIMAL(10,2);
    DECLARE v_3day DECIMAL(10,2);
    DECLARE v_30day DECIMAL(10,2);
    
    -- 1-day rainfall
    SELECT COALESCE(SUM(rainfall_amount), 0) INTO v_1day
    FROM daily_rainfall
    WHERE location_id = p_location_id
      AND rainfall_date = p_target_date;
    
    -- 3-day rainfall
    SELECT COALESCE(SUM(rainfall_amount), 0) INTO v_3day
    FROM daily_rainfall
    WHERE location_id = p_location_id
      AND rainfall_date BETWEEN DATE_SUB(p_target_date, INTERVAL 2 DAY) AND p_target_date;
    
    -- 30-day rainfall
    SELECT COALESCE(SUM(rainfall_amount), 0) INTO v_30day
    FROM daily_rainfall
    WHERE location_id = p_location_id
      AND rainfall_date BETWEEN DATE_SUB(p_target_date, INTERVAL 29 DAY) AND p_target_date;
    
    -- Insert or update rolling calculations
    INSERT INTO rolling_calculations 
        (location_id, calculation_date, one_day_rainfall, three_day_rainfall, thirty_day_rainfall)
    VALUES 
        (p_location_id, p_target_date, v_1day, v_3day, v_30day)
    ON DUPLICATE KEY UPDATE
        one_day_rainfall = v_1day,
        three_day_rainfall = v_3day,
        thirty_day_rainfall = v_30day,
        updated_at = CURRENT_TIMESTAMP;
